#!/usr/bin/env node
/**
 * Fix Prisma TypeScript exports for VS Code language server compatibility.
 *
 * VS Code's TypeScript language server has trouble resolving re-export chains
 * in node_modules/@prisma/client. This script generates direct type declarations
 * instead of using re-exports.
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const projectRoot = path.join(__dirname, "..");
const prismaClientPath = path.join(projectRoot, "node_modules/@prisma/client");
const prismaDotClientPath = path.join(projectRoot, "node_modules/.prisma/client");

// Ensure directories exist
if (!fs.existsSync(prismaClientPath) || !fs.existsSync(prismaDotClientPath)) {
  console.log("Prisma client not installed yet, skipping fix");
  process.exit(0);
}

// Read the actual generated types
const indexDtsPath = path.join(prismaDotClientPath, "index.d.ts");
if (!fs.existsSync(indexDtsPath)) {
  console.error("Generated Prisma types not found");
  process.exit(1);
}

const indexContent = fs.readFileSync(indexDtsPath, "utf-8");

// Create a wrapper that imports and re-exports from the generated types using a more explicit path
const defaultDtsContent = `/**
 * Prisma Client type definitions - auto-generated by fix-prisma-exports.js
 * This file provides proper type exports for VS Code compatibility
 */
export * from ".prisma/client/index"
`;

const wrappedIndexContent = defaultDtsContent;

try {
  fs.writeFileSync(path.join(prismaClientPath, "default.d.ts"), wrappedIndexContent);
  console.log("✓ Fixed @prisma/client/default.d.ts");

  fs.writeFileSync(path.join(prismaClientPath, "index.d.ts"), wrappedIndexContent);
  console.log("✓ Fixed @prisma/client/index.d.ts");

  console.log("✓ Prisma exports configured for VS Code compatibility");
} catch (error) {
  console.error("Failed to fix Prisma exports:", error.message);
  process.exit(1);
}
